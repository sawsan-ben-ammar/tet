"""Render the pinned upstream Online Boutique manifest for the small lab host.

    python lab/k8s/boutique/render.py upstream.yaml > lab/k8s/boutique/boutique.yaml

Changes (all documented, nothing else touched):
  * drop the bundled `loadgenerator` (we run our own, labelled load generator);
  * drop the `frontend-external` LoadBalancer Service (no external exposure);
  * lower CPU *requests* to 20m so 11 services fit on a 2-vCPU node
    (limits are kept, so services can still burst; memory unchanged);
  * add the label `gnn-lab/app: boutique` to every object.
Upstream: GoogleCloudPlatform/microservices-demo, tag in lab/versions.env,
sha256 recorded in UPSTREAM_SHA256 next to this file.
"""
import sys

import yaml


# These two Node services bind to the IPv6 wildcard "[::]" and ignore bindAsync
# errors; on a host without an IPv6 stack the bind fails and server.start()
# throws "server must be bound". Rewrite the bind to the IPv4 wildcard at
# startup. No-op on dual-stack hosts.
IPV4_BIND_PATCH = {"currencyservice": "server.js", "paymentservice": "server.js"}

DROP = {("Deployment", "loadgenerator"), ("ServiceAccount", "loadgenerator"),
        ("Service", "frontend-external")}



IPV4_BIND_JS = r'''// GNN-lab patch: Online Boutique's Node services (currencyservice,
// paymentservice) bind gRPC to the IPv6 wildcard "[::]" and ignore bindAsync
// errors. On a host without an IPv6 stack the bind fails and server.start()
// throws "server must be bound". Preloaded via NODE_OPTIONS=--require, this
// rewrites the listen address to the IPv4 wildcard. No-op on dual-stack hosts.
const grpc = require("/usr/src/app/node_modules/@grpc/grpc-js");
const proto = grpc.Server.prototype;
const orig = proto.bindAsync;
proto.bindAsync = function (addr, creds, cb) {
  if (typeof addr === "string") addr = addr.replace("[::]", "0.0.0.0");
  return orig.call(this, addr, creds, cb);
};
'''

def configmap():
    return {"apiVersion": "v1", "kind": "ConfigMap",
            "metadata": {"name": "gnn-ipv4-bind-patch",
                         "labels": {"gnn-lab/app": "boutique"}},
            "data": {"ipv4-bind.js": IPV4_BIND_JS}}

def main(path):
    with open(path) as fh:
        docs = [d for d in yaml.safe_load_all(fh) if d]
    out = [configmap()]
    for d in docs:
        if (d["kind"], d["metadata"]["name"]) in DROP:
            continue
        d["metadata"].setdefault("labels", {})["gnn-lab/app"] = "boutique"
        if d["kind"] == "Deployment":
            for c in d["spec"]["template"]["spec"]["containers"]:
                req = c.setdefault("resources", {}).setdefault("requests", {})
                req["cpu"] = "20m"
            if d["metadata"]["name"] in IPV4_BIND_PATCH:
                # preload a module that patches grpc bindAsync [::] -> 0.0.0.0
                c.setdefault("env", []).append(
                    {"name": "NODE_OPTIONS", "value": "--require /opt/gnn-patch/ipv4-bind.js"})
                vm = c.setdefault("volumeMounts", [])
                vm.append({"name": "gnn-patch", "mountPath": "/opt/gnn-patch", "readOnly": True})
                vols = d["spec"]["template"]["spec"].setdefault("volumes", [])
                if not any(v.get("name") == "gnn-patch" for v in vols):
                    vols.append({"name": "gnn-patch",
                                 "configMap": {"name": "gnn-ipv4-bind-patch"}})
        out.append(d)
    sys.stdout.write("# GENERATED by render.py from the pinned upstream manifest - do not edit\n")
    sys.stdout.write(yaml.safe_dump_all(out, sort_keys=False))


if __name__ == "__main__":
    main(sys.argv[1])
